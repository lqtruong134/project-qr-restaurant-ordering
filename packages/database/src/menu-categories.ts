export function restaurantProductCategoryIndex(productCode: string) {
  const code = restaurantProductCategoryCodes[productCode];
  const index = restaurantCategories.findIndex((category) => category[0] === code);
  if (index < 0) throw new Error('Thiếu phân loại cho món ' + productCode + '.');
  return index;
}
