export function restaurantCatalogIngredientLocation(code: string) {
  if (dryIngredients.has(code)) return 'KHO-KHO';
  if (['BUTTER', 'PANDAN', 'COCONUTWATER'].includes(code)) return 'QUAY-NUOC';
  return 'KHO-BEP';
}

