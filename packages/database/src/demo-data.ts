export function ingredientLocation(code: string) {
  if (
    [
      'TEA',
      'COFFEE',
      'MILK',
      'KUMQUAT',
      'HONEY',
      'HERBAL',
      'YOGURT',
      'FRUIT',
      'CREAM',
      'ALMOND',
      'GELATIN',
      'COCONUTMILK',
      'MANGO',
      'ORANGE',
      'LEMON',
      'BOTTLEDWATER',
      'COCONUT',
      'BANANA',
      'FRESHMILK',
      'STRAWBERRY',
    ].includes(code)
  )
    return 'QUAY-NUOC';
  if (
    [
      'RICE',
      'RICEPAPER',
      'OIL',
      'SAUCE',
      'SUGAR',
      'PEPPER',
      'PEANUT',
      'SOYSAUCE',
      'CORNSTARCH',
      'TAMARIND',
      'SALT',
      'RICEFLOUR',
      'RICESTICKY',
      'NORI',
      'MAMRUOC',
      'OYSTERSAUCE',
    ].includes(code)
  )
    return 'KHO-KHO';
  return 'KHO-BEP';
}

